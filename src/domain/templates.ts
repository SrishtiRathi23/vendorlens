import type { EventKind } from "@/domain/categories";
import type { PlanDraftAi } from "@/domain/contracts";

type Draft = PlanDraftAi;
type Req = Draft["requirements"][number];
type TaskDraft = Draft["tasks"][number];
type IdeaDraft = Draft["ideas"][number];

const req = (ref: string, r: Omit<Req, "ref">): Req => ({ ref, ...r });
const task = (
  ref: string,
  title: string,
  leadDays: number,
  priority: TaskDraft["priority"],
  category: TaskDraft["category"] = null,
  dependsOn: string[] = [],
): TaskDraft => ({
  ref,
  title,
  category,
  leadDays,
  priority,
  dependsOn,
});
const idea = (
  section: IdeaDraft["section"],
  title: string,
  description: string,
  whyItFits: string,
  dietTags: IdeaDraft["dietTags"] = [],
): IdeaDraft => ({
  section,
  title,
  description,
  whyItFits,
  dietTags,
});

